/**
 * Returns the resolved theme palette according to the current color mode (dark or light)
 */
export const getResolvedTheme = (
  themeId: ThemeId,
  colorMode: ColorMode = 'dark'
): ThemeColors & { id: ThemeId; name: string; tagline: string } => {
  const theme = THEMES[themeId] || THEMES.cyan;
  const colors = theme[colorMode] || theme.dark;
  return {
    ...colors,
    id: theme.id,
    name: theme.name,
    tagline: theme.tagline,
  };
};

/**
 * Injects CSS variables and attributes to document element
 */
export const applyThemeToCSS = (theme: ThemeConfig, colorMode: ColorMode = 'dark') => {
  const root = document.documentElement;
  const resolved = theme[colorMode] || theme.dark;

  root.style.setProperty('--accent-cyan', resolved.accentCyan);
  root.style.setProperty('--accent-violet', resolved.accentViolet);
  root.style.setProperty('--accent-emerald', resolved.accentEmerald);
  root.style.setProperty('--accent-gradient', resolved.accentGradient);
  root.style.setProperty('--bg-deep', resolved.bgDeep);
  root.style.setProperty('--bg-surface', resolved.bgSurface);
  root.style.setProperty('--bg-card', resolved.bgCard);
  root.style.setProperty('--border-subtle', resolved.borderSubtle);
  root.style.setProperty('--border-glow', resolved.borderGlow);
  root.style.setProperty('--text-main', resolved.textMain);
  root.style.setProperty('--text-muted', resolved.textMuted);
  root.style.setProperty('--text-dim', resolved.textDim);

  root.setAttribute('data-theme', theme.id);
  root.setAttribute('data-color-mode', colorMode);
};
